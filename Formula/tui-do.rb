# Homebrew formula for tui-do.
#
# Builds from source deliberately, rather than pouring a downloaded binary. A binary
# fetched over the network carries the com.apple.quarantine attribute, so Gatekeeper
# refuses it with "the developer cannot be verified" unless it is signed and notarised,
# which needs a paid Apple Developer account. Something compiled locally never acquires
# the attribute at all, so the problem does not arise instead of being solved.
class TuiDo < Formula
  desc "Fast, local-first terminal client for Vikunja"
  homepage "https://github.com/sjwasko/tui-do"
  url "https://github.com/sjwasko/tui-do/archive/refs/tags/v1.0.0.tar.gz"
  sha256 "818e2538e75438bc8cc2bf35f854f58c9570361950160b38aab9f43084f067de"
  license any_of: ["MIT", "Apache-2.0"]
  head "https://github.com/sjwasko/tui-do.git", branch: "main"

  depends_on "rust" => :build

  def install
    # `path:` is load-bearing. The repository root is a *virtual* manifest -- a
    # `[workspace]` with no `[package]` -- so the default `std_cargo_args`, which passes
    # `--path .`, fails with:
    #
    #   error: found a virtual manifest at `.../Cargo.toml` instead of a package manifest
    #
    # The binary lives in `crates/tui-do`. Verified 2026-09-07 by running both forms.
    system "cargo", "install", *std_cargo_args(path: "crates/tui-do")

    # Shell completions are generated by the binary that was just built, so they cannot
    # drift from the flags it actually accepts.
    generate_completions_from_executable(bin/"tui-do", "completions", shells: [:bash, :zsh, :fish])
  end

  def caveats
    <<~EOS
      tui-do has no first-run wizard and writes no config for you, so the first run
      stops with "could not read .../config.yaml: No such file or directory".

      On macOS it looks here, which is not the path the README's Linux examples use:

        ~/Library/Application Support/tui-do/config.yaml

      The minimum is a URL and somewhere to find an API token, which you create in
      Vikunja under Settings -> API tokens:

        server:
          url: https://vikunja.example.com
          token_file: token

      A relative token_file resolves beside the config that names it, so writing it
      that way keeps the pair copyable to another machine.

      Token scopes are not obvious and an incomplete token fails in a way that reads
      like a wrong one. See "Token permissions":

        #{homepage}#token-permissions
    EOS
  end

  test do
    assert_match "tui-do #{version}", shell_output("#{bin}/tui-do --version")

    # A missing config must fail with a diagnostic rather than a panic. The workspace
    # denies `unwrap` and `panic` in production code, so this asserts that gate end to
    # end on the packaged artifact.
    output = shell_output("#{bin}/tui-do 2>&1", 1)
    assert_match "config.yaml", output
    refute_match "panicked", output
  end
end
