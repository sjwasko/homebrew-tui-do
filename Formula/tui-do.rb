# Homebrew formula for tui-do.
#
# Installs the release's prebuilt aarch64-apple-darwin binary. Until 2026-11-09 this built
# from source, which pulled llvm (1.6 GB) and rust (432 MB) onto a clean Mac to produce an
# 11 MB binary. That was the price of not having a macOS release asset; v1.1.0 is the first
# release that carries one.
#
# Gatekeeper is not a problem for this route. Measured on a Mac 2026-09-07: quarantine is
# set by the downloading application opting in. Browsers do; curl and Homebrew do not. An
# arm64 binary must be signed to run at all, and ad-hoc signing is enough; rustc applies it
# while linking.
#
# The release workflow refuses to publish a macOS binary that links anything outside
# /usr/lib and /System, so the binary depends on no Homebrew library.
#
# Apple Silicon only, the same as the release. On an Intel Mac, build from source:
# https://github.com/sjwasko/tui-do#building-from-source
class TuiDo < Formula
  desc "Fast, local-first terminal client for Vikunja"
  homepage "https://github.com/sjwasko/tui-do"
  url "https://github.com/sjwasko/tui-do/releases/download/v1.1.0/tui-do-v1.1.0-aarch64-apple-darwin.tar.gz"
  version "1.1.0"
  sha256 "afe29b3f62ef762f1f94d6b884d08803f13fed6eb9e7bc15118269fa13f25875"
  license any_of: ["MIT", "Apache-2.0"]

  depends_on arch: :arm64
  depends_on :macos

  def install
    # The tarball has one top-level directory, which Homebrew strips before this runs.
    bin.install "tui-do"
    doc.install "README.md", "THIRD-PARTY-LICENSES.md"

    # Generated by the binary just installed, so they cannot drift from the flags it accepts.
    generate_completions_from_executable(bin/"tui-do", "completions", shells: [:bash, :zsh, :fish])
  end

  def caveats
    <<~EOS
      To connect to your Vikunja server, run:

        tui-do login

      It asks for the server, opens Vikunja's API-token page, checks the token you
      paste, and writes the config to:

        ~/Library/Application Support/tui-do/

      Token scopes are not obvious. If login says one is missing, see:

        #{homepage}#token-permissions
    EOS
  end

  test do
    assert_match "tui-do #{version}", shell_output("#{bin}/tui-do --version")

    # A missing config must fail with a diagnostic rather than a panic. The workspace
    # denies `unwrap` and `panic` in production code, so this checks that end to end on
    # the installed binary.
    output = shell_output("#{bin}/tui-do 2>&1", 1)
    assert_match "config.yaml", output
    refute_match "panicked", output
  end
end
